const LOCALIZATION_MAPS = { fr: FR, 'es-ES': ES, 'es-419': ES, 'pt-BR': PT_BR, ru: RU, tr: TR, ja: JA };
const CHOICE_LOCALIZATION_MAPS = { fr: CHOICE_FR, 'es-ES': CHOICE_ES, 'es-419': CHOICE_ES, 'pt-BR': CHOICE_PT_BR, ru: CHOICE_RU, tr: CHOICE_TR, ja: CHOICE_JA };

function applySlashLocalizations(commandJson) {
    localizeNode(commandJson, commandJson.name);
    return commandJson;
}

function localizeNode(node, path) {
    const localizations = getDescriptionLocalizations(path) || {};
    if (node.description) {
        // Newly added commands may not have translated copy yet. Keep the
        // command deployable in every supported locale until translations land.
        node.description_localizations = withEnglishFallbacks(localizations, node.description);
    }

    if (Array.isArray(node.choices)) {
        for (const choice of node.choices) {
            const choiceLocalizations = getChoiceLocalizations(path, choice.value) || {};
            choice.name_localizations = {
                fr: choiceLocalizations.fr || choice.name,
                'es-ES': choiceLocalizations['es-ES'] || choice.name,
                'es-419': choiceLocalizations['es-419'] || choice.name,
                'pt-BR': choiceLocalizations['pt-BR'] || choice.name,
                ru: choiceLocalizations.ru || choice.name,
                tr: choiceLocalizations.tr || choice.name,
                ja: choiceLocalizations.ja || choice.name,
            };
        }
    }

    if (!Array.isArray(node.options)) return;
    for (const option of node.options) {
        localizeNode(option, `${path}.${option.name}`);
    }
}

function withEnglishFallbacks(localizations, description) {
    return {
        fr: localizations.fr || description,
        'es-ES': localizations['es-ES'] || description,
        'es-419': localizations['es-419'] || description,
        'pt-BR': localizations['pt-BR'] || description,
        ru: localizations.ru || description,
        tr: localizations.tr || description,
        ja: localizations.ja || description,
    };
}

function getDescriptionLocalizations(path) {
    const result = {};
    for (const [locale, map] of Object.entries(LOCALIZATION_MAPS)) {
        if (map[path]) result[locale] = map[path];
    }
    return Object.keys(result).length ? result : null;
}

function getChoiceLocalizations(path, value) {
    const key = `${path}.${value}`;
    const result = {};
    for (const [locale, map] of Object.entries(CHOICE_LOCALIZATION_MAPS)) {
        if (map[key]) result[locale] = map[key];
    }
    return Object.keys(result).length ? result : null;
}

